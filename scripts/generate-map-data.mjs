import { readFile, writeFile } from "node:fs/promises";

// Inputs from pret/pokecrystal: data/maps/maps.asm,
// data/maps/landmarks.asm, constants/landmark_constants.asm.
const [mapsPath, landmarksPath, constantsPath, revision] = process.argv.slice(2);
if (!mapsPath || !landmarksPath || !constantsPath || !revision) {
  throw new Error("Usage: node scripts/generate-map-data.mjs maps.asm landmarks.asm landmark_constants.asm <source-commit>");
}
const [maps, landmarks, constants] = await Promise.all(
  [mapsPath, landmarksPath, constantsPath].map((path) => readFile(path, "utf8"))
);
const ids = [...constants.matchAll(/^\s*const (LANDMARK_\w+)/gm)].map((match) => match[1]);
const entries = [...landmarks.matchAll(/^\s*landmark\s+(-?\d+),\s*(-?\d+),\s*(\w+)/gm)];
const names = new Map([...landmarks.matchAll(/^(\w+):\s*db "([^"]+)@"/gm)]
  .map((match) => [match[1], match[2].replaceAll("<BSP>", " ")]));
const kantoStart = ids.indexOf("LANDMARK_PALLET_TOWN");
const otherStart = ids.indexOf("LANDMARK_FAST_SHIP");
if (entries.length !== otherStart + 1 || kantoStart < 1) throw new Error("Unexpected landmark table");
const data = {};
for (let index = 1; index < entries.length; index += 1) {
  const [, x, y, name] = entries[index];
  const label = names.get(name);
  if (!label) throw new Error(`Missing landmark name: ${name}`);
  data[index] = {
    key: ids[index].slice("LANDMARK_".length),
    name: label,
    region: index < kantoStart ? "JOHTO" : index < otherStart ? "KANTO" : "UNKNOWN",
    x: Number(x), y: Number(y)
  };
}
const order = [...maps.matchAll(/^\s*dw MapGroup_(\w+)/gm)].map((match) => match[1]);
const groups = {};
let group;
for (const line of maps.split("\n")) {
  const header = line.match(/^MapGroup_(\w+):/);
  if (header) {
    group = order.indexOf(header[1]) + 1;
    if (!group) throw new Error(`Unknown group: ${header[1]}`);
    groups[group] = [];
  }
  const map = line.match(/^\s*map \w+,\s*\w+,\s*\w+,\s*(LANDMARK_\w+),/);
  if (map) {
    const id = ids.indexOf(map[1]);
    if (!group || id < 0 || id >= entries.length) throw new Error(`Unknown landmark: ${line}`);
    groups[group].push(id);
  }
}
if (order.length !== 26 || Object.values(groups).some((group) => group.length === 0)) {
  throw new Error("Unexpected map group table");
}
const content = `// Generated by scripts/generate-map-data.mjs; do not hand-edit.
// Source: https://github.com/pret/pokecrystal/tree/${revision}
// data/maps/maps.asm, data/maps/landmarks.asm, constants/landmark_constants.asm
// Coordinates are the game's 160 × 144 town-map coordinates, before OAM offsets.
import type { Region } from "./types.js";

export interface Landmark { key: string; name: string; region: Region; x: number; y: number }

export const LANDMARKS: Record<number, Landmark> = {
${Object.entries(data).map(([id, landmark]) => `  ${id}: ${JSON.stringify(landmark)}`).join(",\n")}
};

// Each array index + 1 is the map number within that group.
export const MAP_LANDMARKS: Record<number, readonly number[]> = {
${Object.entries(groups).map(([group, ids]) => `  ${group}: [${ids.join(", ")}]`).join(",\n")}
};
`;
await writeFile(new URL("../src/shared/map-data.ts", import.meta.url), content);
console.log(`Generated ${entries.length - 1} landmarks and ${Object.values(groups).flat().length} maps in ${order.length} groups`);
