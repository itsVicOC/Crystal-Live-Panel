import { readFile, writeFile } from "node:fs/promises";

const [constantsPath, attributesPath, revision] = process.argv.slice(2);
if (!constantsPath || !attributesPath || !revision) {
  throw new Error("Usage: node scripts/generate-route-data.mjs map_constants.asm attributes.asm <source-commit>");
}
const [constants, attributes] = await Promise.all([constantsPath, attributesPath].map((path) => readFile(path, "utf8")));
const maps = new Map();
let group = 0;
let number = 0;
for (const line of constants.split("\n")) {
  if (/^\s*newgroup \w+/.test(line)) { group += 1; number = 0; }
  const match = line.match(/^\s*map_const (\w+),\s*(\d+),\s*(\d+)/);
  if (match) {
    number += 1;
    maps.set(match[1], { id: `${group}:${number}`, width: Number(match[2]) * 2, height: Number(match[3]) * 2 });
  }
}
const connections = new Map();
let current;
for (const line of attributes.split("\n")) {
  const header = line.match(/^\s*map_attributes \w+,\s*(\w+),/);
  if (header) { current = header[1]; connections.set(current, {}); }
  const connection = line.match(/^\s*connection (north|south|west|east),\s*\w+,\s*(\w+),\s*(-?\d+)/);
  if (connection) {
    const [, direction, target, rawOffset] = connection;
    const sourceMap = maps.get(current);
    const targetMap = maps.get(target);
    if (!sourceMap || !targetMap) throw new Error(`Unknown connection: ${line}`);
    const vertical = direction === "north" || direction === "south";
    const start = Math.max(0, Number(rawOffset) * 2);
    const end = Math.min(vertical ? sourceMap.width : sourceMap.height,
      Number(rawOffset) * 2 + (vertical ? targetMap.width : targetMap.height)) - 1;
    if (end < start) throw new Error(`Disconnected maps: ${line}`);
    const middle = (start + end) / 2;
    const local = vertical
      ? [middle, direction === "north" ? 0 : sourceMap.height - 1]
      : [direction === "west" ? 0 : sourceMap.width - 1, middle];
    connections.get(current)[direction] = { target, local };
  }
}
const routes = [...maps].filter(([key]) => /^ROUTE_\d+(?:_(?:NORTH|SOUTH))?$/.test(key));
if (group !== 26 || routes.length !== 47) throw new Error("Unexpected route map table");
const content = `// Generated by scripts/generate-route-data.mjs; do not hand-edit.
// Source: https://github.com/pret/pokecrystal/tree/${revision}
// constants/map_constants.asm and data/maps/attributes.asm.
// Dimensions and exit coordinates use player steps (two steps per map block).
export type Point = readonly [number, number];
export type MapEdge = "north" | "south" | "west" | "east";
export interface RoadMap { key: string; width: number; height: number; exits: Partial<Record<MapEdge, { target: string; local: Point }>> }

export const ROAD_MAPS: Record<string, RoadMap> = {
${routes.map(([key, { id, width, height }]) => `  "${id}": ${JSON.stringify({ key, width, height, exits: connections.get(key) ?? {} })}`).join(",\n")}
};
`;
await writeFile(new URL("../src/shared/route-data.ts", import.meta.url), content);
console.log(`Generated ${routes.length} outdoor road maps, including both parts of Route 10`);
